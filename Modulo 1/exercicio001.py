n1 = float (input('Digite o primeiro número: ')) #input() é uma função que permite ao usuário digitar um valor
n2 = float (input('Digite o segundo número: '))
s = n1 + n2 
print ('A soma entre {} e {} é igual a {}'.format(n1, n2, s)) #print() é uma função que exibe uma mensagem na tela e format() é um método que permite inserir valores em uma string

#tipos primitivos
#int - números inteiros
#float - pontos flutuantes/números reais
#str - strings/textos
#bool - valores lógicos (True ou False)